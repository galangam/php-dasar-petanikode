<?php

$score = 0;

// operator increment menggunakan simbol ++ untuk menambah +1 (tambah satu)
$score++;      // 0 + 1 = 1
$score++;      // 1 + 1 = 2
$score++;     // 2 + 1 = 3

// sedangkan decrement menggunakan simbol -- untuk mengurangi -1 (kurangi dengan satu).
$score--;       // 3 - 1 = 2
$score--;       // 2 - 1 = 1
$score--;       // 1 - 1 = 0
$score--;       // 0 - 1 = -1 
$score--;       // -1 - 1 = -2 

// untuk menampilkan hasil akhir score yaitu -2
echo $score;